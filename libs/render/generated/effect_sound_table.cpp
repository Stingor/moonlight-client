// LE BRUIT D'UN EFFET.
//
// Le client joue le bruit d'un effet dans le répartiteur de mise à jour des
// effets : 491 cas, indexés par l'identifiant d'effet lui-même.
//
// ⚠ ET TROIS FONCTIONS LE JOUENT. Le répartiteur ci-dessus en porte 293,
// 58 sont joués par la fonction qui BÂTIT l'effet — scripts/client_effect_handlers.json —
// et 10 par les cas du répartiteur des ÉMETTEURS, que ni l'un ni l'autre ne
// porte : scripts/client_effect_emitters.json. Ne lire que le premier laissait
// muets des effets dont le bruit était relevé — le soin du prêtre en était,
// et EF_PHARMACY_OK, à onze sites d'émission, en était aussi. Et 7 sont mis
// en file par une CLASSE à sa naissance : scripts/client_effect_class_sounds.json.
//
// ⚠ ET CHAQUE BRUIT A SON TIC. Le client en joue beaucoup à un tic PRÉCIS de
// l'instance et non à sa naissance — trente-sept pour l'onde de Bash, soixante
// pour Impositio Manus —, et un effet peut en jouer plusieurs à des tics
// différents. Le tic se lit dans les GARDES de chaque appel :
// scripts/client_effect_sound_ticks.json, interprété par scripts/tics_des_sons.py.
// Ici 191 rangées sonnent après la naissance. C'est ce qui lève le refus des
// effets à plusieurs bruits : 128 en restaient écartés faute de savoir lequel
// jouer, 471 appels restent non résolus (switch sur l'âge, nom non lu) et 3
// appels sont PÉRIODIQUES : leur rangée porte sa période, et le lecteur les
// rejoue tant que l'effet vit — sauf ceux dont le SEMIS se charge déjà, voir
// `EffectNodePattern::sound_at_sowing`.
//
// ⚠ UNE GARDE SUR LE PARAMÈTRE DU BÂTISSEUR SE TRANCHE AU SITE, par l'argument
// que le cas empile : un même bâtisseur fait sonner un bruit pour un effet et
// le tait pour son voisin. 65 bruits se taisent ainsi, chez 41 effets.
//
// ⚠ ET LE LECTEUR DE `.str` A SA PROPRE FILE : 230 bruits de plus, relevés par
// scripts/oracle_du_lecteur_str.py ; 8 de ses identifiants sonnaient déjà
// pareil par un autre relevé. Certains ne sonnent qu'une fois sur N, ou que
// sur un porteur ordinaire : voir `EffectSoundEntry::one_in`.
//
// ⚠ Le bruit n'est pas rangé sous la COMPÉTENCE mais sous l'EFFET : le client le
// déclenche dans la fonction de mise à jour propre à chaque identifiant. Deux
// compétences qui partagent un effet partagent son bruit, et une compétence sans
// effet n'en fait aucun. Une table rangée par compétence ne pouvait pas les
// trouver.
//
// Les chemins sont relatifs au dossier des sons du client, et s'écrivent comme
// dans l'archive.
//
// ⚠ Fichier ENGENDRÉ par scripts/gen_client_effect_sounds.py depuis le relevé
// scripts/client_effect_sounds.json, pas écrit à la main.

