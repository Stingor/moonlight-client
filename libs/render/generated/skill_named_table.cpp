// Les effets qu'une action de COMPÉTENCE désigne par un NOM.
//
// Cent quarante-deux compétences de quatrième classe ne nomment leur effet
// que par une chaîne, résolue dans une table de DONNÉES que l'installation
// porte — voir ro::formats::NamedEffectTable. Sans ce chemin, elles ne
// montrent rien : ni la table des effets de compétence ni celle des
// patrons procéduraux ne les connaissent.
//
// Chaque action est rangée sous l'identifiant de sa compétence, confirmé
// pour 140 d'entre elles.
//
// ⚠ LE SLOT EST LE MOMENT où l'effet se joue :
//     slot 8   l'incantation, à sa pose
//     slot 9   l'incantation
//     slot 11  la compétence sans dégâts
//     slot 12  la compétence posée sur une case
//     slot 15  le paquet des dégâts, sur la source ou la cible
//     slot 16  l'impact, sur qui reçoit le coup
//
// ⚠ Fichier ENGENDRÉ par scripts/gen_client_skill_named_effects.py depuis les
// relevés scripts/client_named_effect_actions.json,
// scripts/client_named_effect_carriers.json et
// scripts/client_skill_action_cases.json, pas écrit à la main.

