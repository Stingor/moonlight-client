// L'EFFET d'une compétence, et SUR QUI il naît.
//
// Le visuel d'une compétence offensive ne vient PAS du chemin d'incantation
// mais de celui des DÉGÂTS : le serveur annonce le coup, le client le range sur
// l'ATTAQUANT, et son répartiteur fait naître les effets. Trois sources :
//
//   le répartiteur des dégâts,
//   la carte des effets visés,
//   le répartiteur des compétences SANS dégâts.
//
// ⚠ NE GARDE QUE CE QUI SE DESSINE, ET IL Y A DEUX FAÇONS. Le relevé porte la
// suite entière des effets de chaque compétence. On garde le premier qui a un
// FICHIER — cherché dans les deux tables du client, la seconde étant celle qui
// nomme les effets des compétences classiques — et, à défaut, le premier que
// nos tables PROCÉDURALES savent dessiner.
//
// ⚠ ET « DESSINÉ » N'EST PAS « MONTRÉ ». Un effet d'acteur — une teinte, un bit
// du mot de rendu, une pose — se montre sans rien dessiner, et le chemin d'une
// compétence SÈME : un effet qui ne pose aucune géométrie n'entre pas ici.
//
// Chaque couple se vérifie par son nom, et c'est ce qui prouve qu'aucun n'a été
// tiré du mauvais cas : WZ_FIREPILLAR joue FirePillar, AS_SONICBLOW joue
// SonicBlow, KN_PIERCE joue Pierce, MC_CARTREVOLUTION joue CartRevolution,
// NPC_SUICIDE joue suicide.
//
