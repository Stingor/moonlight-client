std::optional<ParsedPacket> ParsedPacketFor(std::uint16_t opcode) {
  const auto found = std::ranges::lower_bound(kParsed, opcode, {},
                                              [](const Entry& entry) { return entry.opcode; });
  if (found == kParsed.end() || found->opcode != opcode) {
    return std::nullopt;
  }
  return ParsedPacket{found->handler, std::span(kOffsets).subspan(found->first, found->count)};
}

std::size_t ParsedPacketCount() { return kParsed.size(); }

